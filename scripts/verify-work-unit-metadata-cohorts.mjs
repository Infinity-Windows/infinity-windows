assert.ok(!process.argv.some(a=>['--build-coverage','--build-contributor-coverage'].includes(a)),'Frozen predecessor source cannot be regenerated by this wrapper');
await runContributorProof(readFileSync(new URL('./fixtures/work-unit-metadata-cohorts-checks.mjs',import.meta.url),'utf8'));
