/**
 * The roots the phone keeps in its persisted cache, derived from the table
 * above rather than hand-kept — this is what used to be `OFFLINE_KEYS` in
 * queryClient.ts.
 */
export const OFFLINE_KEY_ROOTS: ReadonlySet<string> = new Set(
  QUERY_KEY_ROOTS.filter((entry) => entry.offline).map((entry) => entry.root),
);

/**
 * Build a query key for new code. Does not enforce that `root` is
 * registered above — TypeScript cannot check a runtime table like that —
 * but `queryKeys.test.ts` does, on every root actually used in the app, so
 * an unregistered root still fails, just at test time instead of compile
 * time.
 */
export function qk(root: string, ...parts: unknown[]): readonly unknown[] {
  return [root, ...parts];
}

