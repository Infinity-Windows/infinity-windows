/**
 * The single registry of query-key ROOTS used anywhere in the app.
 *
 * The first element of every TanStack Query key is a root string — this is
 * the table that says what it is and whether the phone keeps it. A root
 * missing from here is a bug: `queryKeys.test.ts` scans app/src for every
 * root actually used in `queryKey:` / `setQueryData` / `getQueryData` calls
 * and fails, by name, on anything not registered here — and fails again if
 * this table lists a root nothing uses. Registering a new root means
 * answering one question: does the phone keep it offline? The `why` field
 * on each `offline: true` entry is the answer, carried over from the field
 * incident that put it there.
 *
 * `OFFLINE_KEY_ROOTS`, derived below, is what `queryClient.ts` persists to
 * localStorage. Flip `offline` here and the persister follows — there is no
 * second list to remember to update.
 */
export interface QueryKeyRootEntry {
  root: string;
  /** Does the phone keep this query when it has no signal? */
  offline: boolean;
  /**
   * The field incident (or reasoning) that decided the flag above, in the
   * repo's own voice. Required in spirit for every `offline: true` entry;
   * optional for `false` ones that have never needed a reason yet.
   */
  why?: string;
}

