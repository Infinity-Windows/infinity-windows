// QC overlay for new-design-qc-continuity.spec.ts (saved-record continuity,
// 2026-10-06).
//
// Built on the UNCHANGED base designContinuityFixtures.ts (openContinuityPage,
// role owner), NOT on designRecordContinuityFixtures.ts: that file's
// FORBIDDEN_MUTATIONS deliberately lists record_qc_decision, and loosening it
// would weaken the photo and crew specs. Everything here is registered AFTER
// the base install, so it wins only for the exact routes it names; every other
// REST write still meets the base refusal screen (base.log.unexpectedWrites).
//
//   - POST rpc/record_qc_decision: the simulated server. The decision id is
//     generated by the APP (Qc.tsx decisionIdFor, crypto.randomUUID) and sent
//     as p_decision_id; migration 20261041000000 record_qc_decision stores the
//     event under that id and returns it. So this handler stores and returns
//     the app's id — it is NOT a server-minted id, and the legacy decision has
//     no revision. Exactly one well-formed Pass is accepted; anything else is
//     logged and refused with 409. This handler is the only place the QC state
//     (one qc_decision_events row, one qc_checks row) ever changes.
//   - GET qc_checks / qc_decision_events, and the two exact project_openings
//     selects Qc.tsx's queue and history send: served from that state, cloned,
//     with only the filters those readers send modelled (eq, in, not.in on
//     named columns). Any other filter is answered 400 and logged.
//     project_openings GETs with any other select fall back to the base.
//   - GET profiles with select "id,display_name" and id=in.(TEST_USER): the
//     history's reviewer join only. Every other profiles read falls back to
//     the base, so the profile / design preference stays the base's live row.
//
// A `request` listener and a `requestfinished` listener count every POST to
// rpc/record_qc_decision attempted and completed — the browser's own ledger.
//
// Limits: one synthetic OWNER in one browser context; no SQL (dedupe,
// transaction, points), RLS, auth or PostgREST is executed; the legacy QC
// history only — not the dormant unit final-QC authority, an installed PWA or
// physical field proof. The reviewer name and project join are fixture answers.

